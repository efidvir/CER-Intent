#!/usr/bin/env python3
"""
tfs_to_ceragon_twin.py
======================
Convert a CER-Intent / TeraFlowSDN topology snapshot into a Ceragon ns-3 twin
topology file (``.twin``) understood by ``ns3::CeragonTwinHelper``.

Inputs
------
* ``data/topology_state.json`` (CER-Intent state store: nodes, links, applied
  device configs) - default
* or any dict with ``nodes`` / ``links`` lists (same field names)

Mapping
-------
* Ceragon / Siklu models (resolved with the TFS adapter portfolio rules) become
  radio nodes; everything else (O-CU, O-DU, Core-DC, UPF ...) becomes a ``host``.
* A link between two radio-capable ends becomes a ``link`` (radio hop). The
  product used on the hop is chosen from the end whose band matches the TFS
  link role (``mmwave``/``eband`` -> E/V-band product, ``mw`` -> microwave).
* A link with a non-radio end becomes a ``wire`` (fibre/copper).
* Applied intents (device configs) are translated:
    tsn        -> ``tsn`` line (cycle + express window from the GCL)
    protection -> ``protection=hsb`` (``ab`` on MultiHaul TG)
    sync       -> ``sync=bc``      security -> ``macsec=1``
    energy     -> ``atpc=1 sleep=1``
    acm        -> ``event 0.05 a b min-mod <floor>``
    slice      -> ``slice a b <cos> <bw>``

Usage
-----
    python tfs_to_ceragon_twin.py --input data/topology_state.json \
        --output metro.twin --rain 3,6,90 --auto-flows 3
"""
from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

# ── Portfolio resolution (same rules as ceragon_tfs_adapter/portfolio.py) ──────
_FAMILY_BAND = {
    "IP-20": "MW", "IP-50": "MW", "IP-100": "E-band", "EtherHaul": "E-band", "MultiHaul TG": "V-band",
}
_E_BAND_MODELS = {"IP-20E", "IP-50E", "IP-50EX", "IP-50EXA", "IP-100E", "EH-710TX", "EH-1200TX",
                  "EH-1200FX", "EH-2500FX", "EH-8010FX", "EH-8020FX"}
_V_BAND_MODELS = {"IP-20V", "EH-614TX"}


def _load_portfolio():
    """Try to import the TFS adapter portfolio for exact resolution."""
    here = Path(__file__).resolve()
    for root in (here.parents[2], here.parents[2] / "ceragon_tfs_adapter"):
        if (root / "ceragon_tfs_adapter" / "portfolio.py").exists():
            sys.path.insert(0, str(root))
            try:
                from ceragon_tfs_adapter.portfolio import resolve_model  # type: ignore
                return resolve_model
            except Exception:  # pragma: no cover
                pass
    return None


_RESOLVE = _load_portfolio()


def resolve(model: Optional[str]) -> Optional[Tuple[str, str]]:
    """Return (model, family) for Ceragon products, else None."""
    if not model:
        return None
    if _RESOLVE:
        spec = _RESOLVE(model)
        return (spec.model, spec.family) if spec else None
    s = re.sub(r"[_\s]+", "-", model.upper())
    s = re.sub(r"^(CERAGON|SIKLU|FIBEAIR)-", "", s)
    s = re.sub(r"^IP(\d)", r"IP-\1", s)
    s = re.sub(r"^ETHERHAUL-", "EH-", s)
    s = re.sub(r"^MULTIHAUL-(TG-)?", "MH-", s)
    if s.startswith("IP-100"):
        return s, "IP-100"
    if s.startswith("IP-20"):
        return s, "IP-20"
    if s.startswith("IP-50"):
        return s, "IP-50"
    if s.startswith("EH-"):
        return s, "EtherHaul"
    if s.startswith("MH-"):
        return s, "MultiHaul TG"
    return None


def band_of(model: str, family: str) -> str:
    if model in _E_BAND_MODELS:
        return "E-band"
    if model in _V_BAND_MODELS:
        return "V-band"
    return _FAMILY_BAND.get(family, "MW")


def _safe(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]", "_", name)


# ── Conversion ────────────────────────────────────────────────────────────────
def convert(topo: Dict[str, Any],
            rain: Optional[Tuple[float, float, float]] = None,
            flows: Optional[List[str]] = None,
            auto_flows: int = 0,
            scale_m_per_px: float = 10.0,
            events: Optional[List[str]] = None) -> str:
    nodes = topo.get("nodes", [])
    links = topo.get("links", [])
    devices = topo.get("devices", {}) or {}

    out: List[str] = [
        "# Ceragon ns-3 functional twin - generated by tfs_to_ceragon_twin.py",
        f"# source: {topo.get('source', 'CER-Intent')}  synced: {topo.get('last_synced', '-')}",
        "",
    ]
    info: Dict[str, Tuple[str, Optional[str], Optional[str]]] = {}
    for n in nodes:
        nid = _safe(n["id"])
        r = resolve(n.get("model"))
        model = r[0] if r else "host"
        info[nid] = (model, r[1] if r else None, n.get("role"))
        x = float(n.get("x", 0.0)) * scale_m_per_px
        y = float(n.get("y", 0.0)) * scale_m_per_px
        out.append(f"node {nid:<18} {model:<10} {x:9.1f} {y:9.1f}")
    out.append("")

    degree: Dict[str, int] = {}
    radio_pairs: List[Tuple[str, str]] = []
    for lk in links:
        a, b = _safe(lk["src"]), _safe(lk["dst"])
        if a not in info or b not in info:
            continue
        degree[a] = degree.get(a, 0) + 1
        degree[b] = degree.get(b, 0) + 1
        ma, fa, _ = info[a]
        mb, fb, _ = info[b]
        dist_m = float(lk.get("distance_km") or 0.0) * 1000.0
        role = (lk.get("role") or "").lower()
        if fa is None or fb is None:
            cap = lk.get("capacity_gbps") or 10
            out.append(f"wire {a} {b} rate={int(math.ceil(float(cap)))}Gbps")
            continue
        want = "E-band" if role in ("mmwave", "eband", "e-band") else (
            "V-band" if role in ("vband", "60ghz", "terragraph") else "MW")
        cand = [(ma, fa), (mb, fb)]
        pick = next((m for m, f in cand if band_of(m, f) == want), ma)
        opts = [f"model={pick}"]
        if dist_m > 0:
            opts.append(f"distance={dist_m:.0f}")
        out.append(f"link {a} {b} " + " ".join(opts))
        radio_pairs.append((a, b))
    out.append("")

    # Applied intents -> twin configuration
    for dev_id, dev in devices.items():
        did = _safe(dev_id)
        peers = [p for p in radio_pairs if did in p]
        if not peers:
            continue
        a, b = peers[0] if peers[0][0] == did else (peers[0][1], peers[0][0])
        for ctype, cfg in (dev.get("configs") or {}).items():
            p = (cfg or {}).get("parameters", {}) or {}
            if ctype == "tsn":
                cycle = float(p.get("cycle_time_us", 500))
                gcl = p.get("gate_control_list") or []
                express = next((float(g.get("duration_us", 0)) for g in gcl
                                if str(g.get("gate_mask", "")).startswith("1")), cycle * 0.3)
                out.append(f"tsn {a} {b} {cycle:.0f} {express:.0f} express_mask=0x80")
            elif ctype == "slice":
                bw = p.get("bandwidth_mbps") or p.get("guaranteed_bandwidth_mbps") or 500
                out.append(f"slice {a} {b} 5 {int(bw)}Mbps dscp=34,36 weight=4")
            elif ctype in ("acm", "modulation"):
                floor = p.get("min_modulation") or p.get("acm_min")
                if floor:
                    out.append(f"event 0.05 {a} {b} min-mod {str(floor).replace('-', '').upper()}")
            elif ctype == "protection":
                out.append(f"# protection intent on {a}: applied via link option")
            elif ctype == "security":
                out.append(f"event 0.05 {a} {b} macsec 1")
            elif ctype == "energy":
                out.append(f"event 0.05 {a} {b} atpc 1")
    out.append("")

    # Flows
    flow_lines = list(flows or [])
    if auto_flows and not flow_lines:
        hosts = [n for n, (m, f, r) in info.items() if f is None and degree.get(n, 0) > 0]
        # source: a core / DC host (largest degree, prefer 'core' in name or role)
        src = None
        if hosts:
            src = sorted(hosts, key=lambda h: (("core" not in h.lower()
                                                and "core" not in str(info[h][2] or "").lower()),
                                               -degree.get(h, 0), h))[0]
        # destinations: edge hosts (degree 1) such as O-RUs, else radio tails
        dsts = sorted([h for h in hosts if h != src and degree.get(h, 0) == 1],
                      key=lambda h: ("ru" not in h.lower(), h))
        if not dsts:
            dsts = sorted([n for n, (m, f, r) in info.items() if f is not None and degree.get(n, 0) == 1])
        for i, dst in enumerate(dsts[:auto_flows]):
            if src and dst != src:
                flow_lines.append(f"urllc{i},{src},{dst},15Mbps,46")
                flow_lines.append(f"embb{i},{src},{dst},45Mbps,0")
    for f in flow_lines:
        parts = [x.strip() for x in f.split(",")]
        if len(parts) >= 4:
            dscp = parts[4] if len(parts) > 4 else "0"
            out.append(f"flow {_safe(parts[0])} {_safe(parts[1])} {_safe(parts[2])} {parts[3]} "
                       f"dscp={dscp} start=0.5")
    if rain:
        out.append(f"rain {rain[0]:g} {rain[1]:g} {rain[2]:g}")
    for e in events or []:
        out.append(f"event {e}")
    return "\n".join(out) + "\n"


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--input", default="data/topology_state.json")
    ap.add_argument("--output", default="-")
    ap.add_argument("--rain", help="start,duration,peak_mm_h  e.g. 3,6,90")
    ap.add_argument("--flow", action="append", default=[], help="name,src,dst,rate[,dscp]")
    ap.add_argument("--event", action="append", default=[], help="'<t> <a> <b> <action> [value]'")
    ap.add_argument("--auto-flows", type=int, default=0)
    ap.add_argument("--scale", type=float, default=10.0, help="metres per dashboard pixel")
    args = ap.parse_args(argv)

    topo = json.loads(Path(args.input).read_text(encoding="utf-8"))
    rain = tuple(float(x) for x in args.rain.split(",")) if args.rain else None
    text = convert(topo, rain=rain, flows=args.flow, auto_flows=args.auto_flows,
                   scale_m_per_px=args.scale, events=args.event)
    if args.output == "-":
        sys.stdout.write(text)
    else:
        Path(args.output).write_text(text, encoding="utf-8")
        print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
